<article class="card">
  <h1>Privacy</h1>
  <p class="muted">Last updated October 2026.</p>

  <p>
    UTTT is a free, non-commercial site run by an individual (Faim9). We collect as little as we
    can, never sell data, and show no ads. There is no tracking and no analytics.
  </p>

  <h2>What we store</h2>
  <ul>
    <li>
      <strong>Your account:</strong> username, email address, a hashed password (we can't read it), and,
      if you turn it on, your two-factor secret and hashed recovery codes.
    </li>
    <li>
      <strong>Your games and ratings.</strong> These are public: anyone can see your profile, games, and
      ratings, as on any chess site.
    </li>
    <li>
      <strong>Your signed-in devices:</strong> the browser and system name (e.g. "Firefox on Linux") and
      when each was last active, so you can sign them out in Settings.
    </li>
    <li>
      <strong>Two cookies:</strong> one keeps you signed in, one lets guests reconnect to their games.
      Both are needed for the site to work, so we don't ask for consent. There are no other cookies.
    </li>
  </ul>
  <p>
    Your IP address is used briefly to limit abuse (like too many sign-in attempts) and is not
    stored. Without an account, we store nothing about you except games you play as a guest.
  </p>

  <h2>Who else handles it</h2>
  <ul>
    <li>The server is a computer run by Faim9, in the EU.</li>
    <li>
      <strong>Cloudflare</strong> delivers the site to your browser and stores our encrypted backups in
      the EU.
    </li>
    <li>
      <strong>An email delivery service</strong> sends our two kinds of email: confirming your address
      and resetting your password.
    </li>
    <li>
      <strong>Have I Been Pwned</strong> tells us whether a new password appeared in a data breach. Only
      the first 5 characters of a fingerprint of the password are sent, never the password.
    </li>
  </ul>

  <h2>How long we keep it</h2>
  <p>
    Your account stays until you delete it. Deleting it removes your account, ratings, and sessions
    right away; your games stay in your opponents' histories, without your name. Backups keep a copy
    for up to 7 days, then it's gone for good.
  </p>

  <h2>Your rights</h2>
  <p>
    You can download all your data and delete your account at any time in
    <a href="/account">Settings</a>. For anything else, like correcting your data or asking
    questions, write to <a href="mailto:privacy@uttt.org">privacy@uttt.org</a>. You can also
    complain to your data protection authority.
  </p>
</article>

